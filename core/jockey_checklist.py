def _norm(name):
    value = unicodedata.normalize('NFKC', str(name or ''))
    return ''.join(value.split()).lstrip('☆▲△◇★')


def catalogue():
    """原資料の全35項目。曖昧な名前も隠さず確認待ちとして残す。"""
    return [dict(番号=i, 画像の騎手名=name, 画像の印=mark,
                 画像の主張=text, 状態='未検証' if aliases else '本人・画像表記の確認待ち')
            for i, (name, mark, text, aliases) in enumerate(_DATA, 1)]


def lookup(jockey_name):
    """明示的な本人名/略記だけ照合。条件が成立したという意味ではない。"""
    name = _norm(jockey_name)
    for label, mark, text, aliases in _DATA:
        if name and name in {_norm(a) for a in aliases}:
            status = '未検証'
            if label == '池添':
                status = '連勝/連敗だけの予測利用は既存検証で不採用'
            return dict(label=label, mark=mark, text=text, status=status)
    return None


def display_text(jockey_name, *, for_j5=False):
    item = lookup(jockey_name)
    if item is None:
        return '' if for_j5 else '—（記載なし／本人未特定）'
    prefix = '' if for_j5 else '画像'
    return f"{prefix}{item['mark']}：{item['text']}【{item['status']}・条件未判定】"


